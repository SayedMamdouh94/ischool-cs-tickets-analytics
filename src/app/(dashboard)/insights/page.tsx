import type { Metadata } from "next";
import { DashboardPage } from "@/components/dashboard/dashboard-page";
import { PageActions } from "@/components/dashboard/page-actions";
import { InsightCard } from "@/components/dashboard/insight-card";
import { SectionHeading } from "@/components/dashboard/page-header";
import { EmptyState } from "@/components/dashboard/states";
import { Card, CardContent, CardHeader, CardTitle } from "@/components/ui/card";
import { requireViewer } from "@/lib/auth/dal";
import { describePeriods, type Insight } from "@/lib/analytics/insights";
import { loadInsights } from "@/lib/analytics/insights-loader";
import { resolveFilterContext } from "@/lib/analytics/queries";
import type { SearchParamsRecord } from "@/lib/filters/schema";
import { fmtPct } from "@/lib/format";

export const metadata: Metadata = { title: "Insights" };

const AREAS: { area: Insight["area"]; title: string; question: string }[] = [
  { area: "data", title: "Data caveats", question: "What limits how these figures should be read right now?" },
  { area: "backlog", title: "Outstanding issues", question: "Which projects have more outstanding issues?" },
  { area: "resolution", title: "Resolution", question: "Which topics take longer to resolve, and where are thresholds exceeded?" },
  { area: "trend", title: "Trends", question: "Which topics are taking a larger share of tickets? Were there unusual days?" },
  { area: "recurring", title: "Recurring problems", question: "Which recurring problems deserve operational investigation?" },
  { area: "volume", title: "Volume", question: "How is ticket volume distributed across projects?" },
];

export default function InsightsPage({ searchParams }: PageProps<"/insights">) {
  return (
    <DashboardPage
      title="Insights & Recommendations"
      description="Observations, recommended actions and data caveats generated by deterministic statistical rules from the imported data. Every figure is recomputed for the current filters and links to the view that reproduces it."
      searchParams={searchParams}
      actions={<PageActions />}
    >
      <InsightsContent searchParams={searchParams} />
    </DashboardPage>
  );
}

async function InsightsContent({ searchParams }: { searchParams: Promise<SearchParamsRecord> }) {
  await requireViewer();
  const ctx = await resolveFilterContext(await searchParams);
  const { insights, rules: R, topicPeriods } = await loadInsights(ctx);
  if (insights.length === 0) return <EmptyState title="No insights for this selection" description="There is not enough data in this view for any rule to apply." />;
  const recommendations = insights.filter((i) => i.kind === "recommendation");
  const names = Object.fromEntries(ctx.options.projects.map((p) => [p.code, p.name]));

  return (
    <div className="flex flex-col gap-8">
      {recommendations.length > 0 && (
        <Card className="gap-3 border-primary/30 shadow-xs">
          <CardHeader>
            <CardTitle className="text-sm font-semibold">Recommended actions ({recommendations.length})</CardTitle>
          </CardHeader>
          <CardContent>
            <ol className="list-decimal space-y-1.5 pl-5 text-sm">
              {recommendations.map((i) => (
                <li key={i.id}>
                  <span className="font-medium">{i.title}.</span> <span className="text-muted-foreground">{i.recommendation}</span>
                </li>
              ))}
            </ol>
          </CardContent>
        </Card>
      )}

      {AREAS.map(({ area, title, question }) => {
        const items = insights.filter((i) => i.area === area);
        if (items.length === 0) return null;
        return (
          <section key={area} className="flex flex-col gap-3">
            <SectionHeading title={title} description={question} />
            <div className="grid gap-3 md:grid-cols-2 xl:grid-cols-3">
              {items.map((i) => (
                <InsightCard key={i.id} insight={i} filters={ctx.filters} />
              ))}
            </div>
          </section>
        );
      })}

      <Card className="gap-3 shadow-xs">
        <CardHeader>
          <CardTitle className="text-sm font-semibold">Method</CardTitle>
        </CardHeader>
        <CardContent className="grid gap-2 text-sm text-muted-foreground md:grid-cols-2">
          <p>
            <strong className="text-foreground">Topic trends:</strong> compares each topic&apos;s <em>share</em> of all tickets in the latest period with the preceding period of equal
            length, so a project growing or shrinking does not look like a topic trend. Reported when the topic has at least {R.trend_min_current} tickets, its share changed by at
            least {fmtPct(R.trend_min_change, 0)}, and a two-proportion test reaches z ≥ {R.trend_min_z}.
          </p>
          <p>
            <strong className="text-foreground">Comparison periods:</strong> {describePeriods(topicPeriods, names)}
          </p>
          <p>
            <strong className="text-foreground">Longer resolution:</strong> topics with at least {R.slow_topic_min_n} resolved tickets whose median exceeds the overall median by{" "}
            {R.slow_topic_factor}× or more, ranked by tickets affected.
          </p>
          <p>
            <strong className="text-foreground">Recurring complaints:</strong> a keyword theme covering at least {fmtPct(R.dominant_theme_share, 0)} of a topic with{" "}
            {R.dominant_theme_min_topic}+ tickets, ranked by the number of tickets affected; sessions reported by {R.recurring_min_students}+ different students.
          </p>
          <p>
            <strong className="text-foreground">Unusual days:</strong> detected per project against its own trailing {R.spike_window_days}-day median (robust z ≥ {R.spike_threshold}, at
            least {R.spike_min_count} tickets), ignoring the first {R.spike_rampup_days} days of each intake.
          </p>
          <p>
            <strong className="text-foreground">Labels:</strong> <em>Observation</em> describes the data; <em>Recommendation</em> adds a suggested next step grounded in that evidence;{" "}
            <em>Data caveat</em> limits how figures should be read. Associations are never presented as proven causes. All thresholds are configurable by administrators (Settings →
            Thresholds).
          </p>
          <p className="md:col-span-2">
            No AI model is used. Ticket text is never sent to an external service. Any future AI-assisted classification would be a separate, opt-in feature stored with method{" "}
            <code className="rounded bg-muted px-1">ai_assisted</code>, and would require explicit approval before student messages leave the database.
          </p>
        </CardContent>
      </Card>
    </div>
  );
}
