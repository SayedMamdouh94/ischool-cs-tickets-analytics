import type { Metadata } from "next";
import { DashboardPage } from "@/components/dashboard/dashboard-page";
import { PageActions } from "@/components/dashboard/page-actions";
import { InsightCard } from "@/components/dashboard/insight-card";
import { SectionHeading } from "@/components/dashboard/page-header";
import { EmptyState } from "@/components/dashboard/states";
import { Card, CardContent, CardHeader, CardTitle } from "@/components/ui/card";
import { requireViewer } from "@/lib/auth/dal";
import { RULES, type Insight } from "@/lib/analytics/insights";
import { loadInsights } from "@/lib/analytics/insights-loader";
import { resolveFilterContext } from "@/lib/analytics/queries";
import type { SearchParamsRecord } from "@/lib/filters/schema";
import { fmtPct } from "@/lib/format";

export const metadata: Metadata = { title: "Insights" };

const AREAS: { area: Insight["area"]; title: string; question: string }[] = [
  { area: "backlog", title: "Outstanding issues", question: "Which projects have more outstanding issues?" },
  { area: "resolution", title: "Resolution", question: "Which topics take longer to resolve, and where are thresholds exceeded?" },
  { area: "trend", title: "Trends", question: "Which topics are becoming more frequent? Were there unusual spikes?" },
  { area: "recurring", title: "Recurring problems", question: "Which recurring problems deserve operational investigation?" },
  { area: "volume", title: "Volume", question: "Which project has the highest ticket volume?" },
  { area: "data", title: "Data caveats", question: "What limits how these figures should be read?" },
];

export default function InsightsPage({ searchParams }: PageProps<"/insights">) {
  return (
    <DashboardPage
      title="Insights & Recommendations"
      description="Observations generated by deterministic statistical rules from the database. Every figure is computed live for the current filters and links to the view that reproduces it."
      searchParams={searchParams}
      actions={<PageActions />}
    >
      <InsightsContent searchParams={searchParams} />
    </DashboardPage>
  );
}

async function InsightsContent({ searchParams }: { searchParams: Promise<SearchParamsRecord> }) {
  await requireViewer();
  const ctx = await resolveFilterContext(await searchParams);
  const { insights } = await loadInsights(ctx);
  if (insights.length === 0) return <EmptyState title="No insights for this selection" />;

  return (
    <div className="flex flex-col gap-8">
      {AREAS.map(({ area, title, question }) => {
        const items = insights.filter((i) => i.area === area);
        if (items.length === 0) return null;
        return (
          <section key={area} className="flex flex-col gap-3">
            <SectionHeading title={title} description={question} />
            <div className="grid gap-3 md:grid-cols-2 xl:grid-cols-3">
              {items.map((i) => (
                <InsightCard key={i.id} insight={i} filters={ctx.filters} />
              ))}
            </div>
          </section>
        );
      })}

      <Card className="gap-3 shadow-xs">
        <CardHeader>
          <CardTitle className="text-sm font-semibold">Method</CardTitle>
        </CardHeader>
        <CardContent className="grid gap-2 text-sm text-muted-foreground md:grid-cols-2">
          <p>
            <strong className="text-foreground">Rising/falling topics:</strong> latest period vs. the preceding period of equal length; reported when the current period has at least{" "}
            {RULES.trendMinCurrent} tickets and changed by at least {fmtPct(RULES.trendMinChange, 0)}.
          </p>
          <p>
            <strong className="text-foreground">Longer resolution:</strong> topics with at least {RULES.slowTopicMinN} resolved tickets whose median exceeds the overall median by{" "}
            {RULES.slowTopicFactor}× or more.
          </p>
          <p>
            <strong className="text-foreground">Recurring complaints:</strong> a keyword theme covering at least {fmtPct(RULES.dominantThemeShare, 0)} of a topic with{" "}
            {RULES.dominantThemeMinTopic}+ tickets; sessions reported by two or more different students.
          </p>
          <p>
            <strong className="text-foreground">Spikes:</strong> days whose count exceeds the trailing 28-day median by a robust z-score ≥ 3.5 (and at least 10 tickets).
          </p>
          <p className="md:col-span-2">
            No AI model is used. Ticket text is never sent to an external service. Any future AI-assisted classification would be a separate, opt-in feature stored with
            method <code className="rounded bg-muted px-1">ai_assisted</code>, and would require explicit approval before student messages leave the database.
          </p>
        </CardContent>
      </Card>
    </div>
  );
}
