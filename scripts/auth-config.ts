/**
 * Checks (default) or applies (--apply) the production Supabase Auth settings
 * this application requires:
 *
 *   site_url               = NEXT_PUBLIC_SITE_URL
 *   uri_allow_list         ⊇ NEXT_PUBLIC_SITE_URL + "/**"   (existing entries preserved)
 *   disable_signup         = true                           (invite-only)
 *
 *   ENV_FILE=.env.cloud npm run auth:config [-- --apply]
 *
 * Uses `supabase config diff/push` with a temporary config that DECLARES ONLY
 * these properties — the CLI leaves every undeclared remote setting unchanged —
 * authorized by the Supabase CLI login (no secrets handled here). Idempotent:
 * nothing is pushed when the remote already matches.
 */
import { execFile } from "node:child_process";
import { mkdtempSync, mkdirSync, rmSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import path from "node:path";
import { parseArgs } from "node:util";
import { firstJsonObject } from "./lib/db";
import { requireEnv } from "./lib/env";
import { projectRef } from "./lib/mgmt";

interface Change {
  path: string[];
  class: string;
  declared: boolean;
  local: unknown;
  remote: unknown;
}

function cli(args: string[]): Promise<{ out: string; code: number }> {
  return new Promise((resolve) =>
    execFile("supabase", args, { maxBuffer: 32 * 1024 * 1024, timeout: 180_000, env: { ...process.env, SUPABASE_YES: "1" } }, (err, stdout, stderr) =>
      resolve({ out: `${stdout}\n${stderr}`, code: err ? 1 : 0 }),
    ),
  );
}

function tomlString(s: string): string {
  return JSON.stringify(s); // TOML basic strings share JSON's escaping for these values
}

function writeConfig(dir: string, siteUrl: string, redirects: string[]): void {
  mkdirSync(path.join(dir, "supabase"), { recursive: true });
  writeFileSync(
    path.join(dir, "supabase", "config.toml"),
    [
      "# Generated by scripts/auth-config.ts — declares ONLY the managed auth properties.",
      'project_id = "cs-tickets-analytics-auth"',
      "",
      "[auth]",
      `site_url = ${tomlString(siteUrl)}`,
      `additional_redirect_urls = [${redirects.map(tomlString).join(", ")}]`,
      "enable_signup = false",
      "",
    ].join("\n"),
  );
}

async function diff(dir: string, ref: string): Promise<Change[]> {
  const { out } = await cli(["config", "diff", "--project-ref", ref, "--workdir", dir]);
  const json = firstJsonObject(out);
  if (!json) throw new Error(`supabase config diff returned no result: ${out.slice(0, 300)}`);
  const parsed = JSON.parse(json) as { changes?: Change[]; _tag?: string; error?: { message?: string } };
  if (parsed._tag === "Error") throw new Error(`supabase config diff failed: ${parsed.error?.message}`);
  return (parsed.changes ?? []).filter((c) => c.path[0] === "auth");
}

async function main(): Promise<number> {
  const { values } = parseArgs({ options: { apply: { type: "boolean", default: false } } });
  const ref = projectRef();
  const siteUrl = requireEnv("NEXT_PUBLIC_SITE_URL").replace(/\/$/, "");
  if (!/^https:\/\//.test(siteUrl)) throw new Error("NEXT_PUBLIC_SITE_URL must be an https:// URL for production.");
  const wanted = `${siteUrl}/**`;
  const dir = mkdtempSync(path.join(tmpdir(), "cs-auth-"));

  try {
    // Pass 1: learn the remote redirect list so existing entries are preserved.
    writeConfig(dir, siteUrl, [wanted]);
    let changes = await diff(dir, ref);
    const redirectChange = changes.find((c) => c.path.join(".") === "auth.additional_redirect_urls");
    const remoteRedirects = Array.isArray(redirectChange?.remote) ? (redirectChange!.remote as string[]) : [wanted];
    const merged = [...new Set([...remoteRedirects, wanted])];
    if (merged.join("|") !== [wanted].join("|")) {
      writeConfig(dir, siteUrl, merged);
      changes = await diff(dir, ref);
    }
    const pending = changes.filter((c) => c.declared && c.class === "update");

    console.log(`Auth configuration for project ${ref}`);
    console.log(`  site_url                 → ${siteUrl}`);
    console.log(`  additional_redirect_urls → ${merged.join(", ")}`);
    console.log("  enable_signup            → false (invite-only)");
    if (pending.length === 0) {
      console.log("✓ Remote auth settings already match (nothing to change).");
      return 0;
    }
    for (const c of pending) console.log(`  • ${c.path.join(".")}: ${JSON.stringify(c.remote)} → ${JSON.stringify(c.local)}`);
    if (!values.apply) {
      console.log(`! ${pending.length} setting(s) differ. Re-run with --apply to update them.`);
      return 2;
    }
    const push = await cli(["config", "push", "--project-ref", ref, "--workdir", dir, "--yes"]);
    if (push.code !== 0) throw new Error(`supabase config push failed: ${push.out.slice(-400)}`);
    const after = (await diff(dir, ref)).filter((c) => c.declared && c.class === "update");
    if (after.length > 0) {
      console.error(`✗ ${after.length} setting(s) still differ after push.`);
      return 1;
    }
    console.log(`✓ Applied and verified ${pending.length} setting(s).`);
    return 0;
  } finally {
    rmSync(dir, { recursive: true, force: true });
  }
}

main()
  .then((code) => process.exit(code))
  .catch((err) => {
    console.error(`Auth configuration aborted: ${(err as Error).message}`);
    process.exit(1);
  });
